"""Set up and check the STAGING database on Neon (fake data only).

Run from the backend/ folder with the virtual environment active.

    python scripts/staging_database.py create
        Once. Asks (hidden) for the Neon owner connection string, then creates
        the users sms_migrator and sms_app and the database sms_staging, and
        writes backend/.env.staging (readable only by you). No password is
        ever displayed, and the owner connection string is not stored.

    python scripts/staging_database.py check
        Any time, for example after migrations. Connects as sms_app (from
        .env.staging) and confirms it is still a least-privilege user.

    python scripts/staging_database.py rotate
        Gives sms_migrator and sms_app new random passwords (for example after
        losing this computer, or on a schedule) and writes a new
        backend/.env.staging. The API on Render keeps its old password until
        its DATABASE_URL is replaced with the new one, so do that straight
        away.

Why SQL instead of Neon's "create role" button: Neon makes roles created in
its console, CLI or API members of neon_superuser, which can bypass Row-Level
Security. Roles created with SQL get no such membership.
"""

import argparse
import getpass
import os
import secrets
import sys
from pathlib import Path

import psycopg
from dotenv import dotenv_values
from psycopg import sql
from sqlalchemy.engine import URL, make_url

ENV_FILE = Path(__file__).resolve().parent.parent / ".env.staging"
DATABASE = "sms_staging"
APP_USER = "sms_app"
MIGRATOR = "sms_migrator"
POSTGRES_MAJOR_VERSION = 16
SAFE_SSL_MODES = ("require", "verify-ca", "verify-full")
# Tables whose rows are separated by school with Row-Level Security.
RLS_TABLES = (
    "students",
    "invitations",
    "academic_years",
    "terms",
    "classes",
    "class_teachers",
    "enrolments",
    "attendance_registers",
    "attendance_marks",
    "guardians",
    "student_guardians",
)
# Placeholder until the Vercel address is known (replace it in .env.staging).
PLACEHOLDER_ORIGIN = "https://staging.example.invalid"

ROLE_ATTRIBUTES = "LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS"


class SetupError(Exception):
    """A problem the person running the script can fix."""


def parse_owner_url(raw: str) -> URL:
    """Check the Neon owner connection string before anything connects with it."""
    try:
        url = make_url(raw.strip())
    except Exception:  # noqa: BLE001 (any parse failure means the same thing)
        raise SetupError("That does not look like a connection string.") from None
    if url.get_backend_name() != "postgresql" or not url.host or not url.password:
        raise SetupError(
            "Expected a connection string like postgresql://user:password@host/neondb?sslmode=require"
        )
    if "-pooler" in url.host:
        raise SetupError(
            "That is the pooled connection string. Turn 'Connection pooling' off in Neon's "
            "Connect dialog and copy the direct one."
        )
    if url.query.get("sslmode") not in SAFE_SSL_MODES:
        raise SetupError("The connection string must include sslmode=require (or verify-full).")
    return url


def build_urls(owner: URL, app_password: str, migrator_password: str) -> dict[str, str]:
    """The two connection strings the app uses, on the same host and TLS settings."""

    def url(user: str, password: str) -> str:
        return owner.set(
            drivername="postgresql+psycopg", username=user, password=password, database=DATABASE
        ).render_as_string(hide_password=False)

    return {
        "DATABASE_URL": url(APP_USER, app_password),
        "MIGRATION_DATABASE_URL": url(MIGRATOR, migrator_password),
    }


def libpq(url: str | URL) -> str:
    """psycopg wants plain postgresql://, without SQLAlchemy's +psycopg."""
    return make_url(url).set(drivername="postgresql").render_as_string(hide_password=False)


def env_file_text(urls: dict[str, str]) -> str:
    # Single quotes keep '&' in the URLs safe when the file is loaded by a shell.
    values = {
        "APP_ENV": "production",
        # Used only when you run flask commands against staging from this
        # computer. The Render service has its own, generated by Render.
        "SECRET_KEY": secrets.token_urlsafe(48),
        **urls,
        "FRONTEND_ORIGIN": PLACEHOLDER_ORIGIN,
        "TRUSTED_PROXY_COUNT": "0",
        # Production settings require one; flask commands run from this
        # computer serve no requests, so a local random value is enough. The
        # real shared secret lives only in Vercel's and Render's settings.
        "PROXY_SHARED_SECRET": secrets.token_urlsafe(48),
    }
    lines = [
        "# STAGING settings for running flask commands from this computer. Never commit.",
        "# Load in a subshell: ( set -a; . ./.env.staging; set +a; FLASK_SKIP_DOTENV=1 flask ... )",
    ]
    lines += [f"{key}='{value}'" for key, value in values.items()]
    return "\n".join(lines) + "\n"


def write_env_file(text: str, replace: bool = False) -> None:
    """Write .env.staging, readable only by you (0o600).

    Without `replace`, an existing file is never overwritten. With it, the new
    file is written next to the old one and then swapped in, so the file is
    never left half-written or briefly readable by others.
    """
    target = ENV_FILE.with_name(ENV_FILE.name + ".new") if replace else ENV_FILE
    if replace:
        target.unlink(missing_ok=True)  # left over from an interrupted run
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(text)
    if replace:
        os.replace(target, ENV_FILE)


def create() -> None:
    if ENV_FILE.exists():
        raise SetupError(f"{ENV_FILE.name} already exists, so staging is already set up.")

    owner = parse_owner_url(getpass.getpass("Neon owner connection string (hidden): "))
    # token_urlsafe(32) is 256 bits; Neon requires at least 60. Its characters
    # (A-Z a-z 0-9 - _) need no escaping in SQL or in a URL.
    app_password = secrets.token_urlsafe(32)
    migrator_password = secrets.token_urlsafe(32)
    urls = build_urls(owner, app_password, migrator_password)

    with psycopg.connect(libpq(owner), autocommit=True, connect_timeout=15) as conn:
        major = conn.info.server_version // 10000
        if major != POSTGRES_MAJOR_VERSION:
            raise SetupError(f"The Neon project runs PostgreSQL {major}; create it with 16.")
        taken = conn.execute(
            "SELECT rolname FROM pg_roles WHERE rolname = ANY(%s)", ([APP_USER, MIGRATOR],)
        ).fetchall()
        if (
            taken
            or conn.execute("SELECT 1 FROM pg_database WHERE datname = %s", (DATABASE,)).fetchone()
        ):
            raise SetupError("sms_app, sms_migrator or sms_staging already exists on this server.")

        print("Creating users sms_migrator and sms_app...")
        with conn.transaction():
            for role, password in ((MIGRATOR, migrator_password), (APP_USER, app_password)):
                conn.execute(
                    sql.SQL("CREATE ROLE {} " + ROLE_ATTRIBUTES + " PASSWORD {}").format(
                        sql.Identifier(role), sql.Literal(password)
                    )
                )
            # Creating a database for another owner requires being able to act
            # as that owner, so the Neon owner holds this right only briefly.
            conn.execute(
                sql.SQL("GRANT {} TO CURRENT_USER WITH SET TRUE, INHERIT FALSE").format(
                    sql.Identifier(MIGRATOR)
                )
            )

        print("Creating database sms_staging...")
        conn.execute(
            sql.SQL("CREATE DATABASE {} OWNER {} ENCODING 'UTF8' TEMPLATE template0").format(
                sql.Identifier(DATABASE), sql.Identifier(MIGRATOR)
            )
        )
        conn.execute(sql.SQL("REVOKE {} FROM CURRENT_USER").format(sql.Identifier(MIGRATOR)))

    print("Setting permissions (as sms_migrator, the owner)...")
    with psycopg.connect(libpq(urls["MIGRATION_DATABASE_URL"]), connect_timeout=15) as conn:
        # Same rules as scripts/create_local_database.sql.
        conn.execute("REVOKE ALL ON DATABASE sms_staging FROM PUBLIC")
        conn.execute("GRANT CONNECT ON DATABASE sms_staging TO sms_app")
        conn.execute("REVOKE ALL ON SCHEMA public FROM PUBLIC")
        conn.execute("GRANT USAGE ON SCHEMA public TO sms_app")
        conn.execute(
            "ALTER DEFAULT PRIVILEGES FOR ROLE sms_migrator IN SCHEMA public "
            "GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO sms_app"
        )
        conn.execute(
            "ALTER DEFAULT PRIVILEGES FOR ROLE sms_migrator IN SCHEMA public "
            "GRANT USAGE, SELECT ON SEQUENCES TO sms_app"
        )

    write_env_file(env_file_text(urls))
    print(f"Wrote {ENV_FILE.name} (readable only by you). No password was displayed.")
    print()
    if not run_checks(urls["DATABASE_URL"], expect_tables=False):
        raise SetupError("Some checks failed. Do not deploy; share the output above.")


def rotate() -> None:
    owner = parse_owner_url(getpass.getpass("Neon owner connection string (hidden): "))
    app_password = secrets.token_urlsafe(32)
    migrator_password = secrets.token_urlsafe(32)
    urls = build_urls(owner, app_password, migrator_password)

    with psycopg.connect(libpq(owner), autocommit=True, connect_timeout=15) as conn:
        found = {
            row[0]
            for row in conn.execute(
                "SELECT rolname FROM pg_roles WHERE rolname = ANY(%s)", ([APP_USER, MIGRATOR],)
            )
        }
        if found != {APP_USER, MIGRATOR}:
            raise SetupError("sms_app and sms_migrator do not both exist. Run create first.")
        print("Setting new passwords for sms_migrator and sms_app...")
        with conn.transaction():
            for role, password in ((MIGRATOR, migrator_password), (APP_USER, app_password)):
                conn.execute(
                    sql.SQL("ALTER ROLE {} PASSWORD {}").format(
                        sql.Identifier(role), sql.Literal(password)
                    )
                )

    write_env_file(env_file_text(urls), replace=True)
    print(f"Wrote {ENV_FILE.name} (readable only by you). No password was displayed.")
    print()
    passed = run_checks(urls["DATABASE_URL"])
    print()
    print("Now replace DATABASE_URL on Render with the new one from .env.staging:")
    print("  the API cannot open new database connections until you do.")
    if not passed:
        raise SetupError("Some checks failed. Do not deploy; share the output above.")


def run_checks(database_url: str, expect_tables: bool = True, require_tls: bool = True) -> bool:
    """Connect as the API's user and confirm what it can and cannot do.

    `require_tls` is turned off only by the automated tests, whose local
    database does not use TLS.
    """
    results: list[tuple[bool, str]] = []

    def check(passed: bool, message: str) -> None:
        results.append((bool(passed), message))

    with psycopg.connect(libpq(database_url), connect_timeout=15) as conn:
        user, database = conn.execute("SELECT current_user, current_database()").fetchone()
        check(user == APP_USER, f"connected as {user}")
        if require_tls:
            # Asked of this computer's side of the connection, the part that
            # crosses the internet. (Neon's proxy ends TLS before the database,
            # so the database's own pg_stat_ssl view reports no TLS.)
            check(conn.pgconn.ssl_in_use, "connection is encrypted (TLS)")

        superuser, bypassrls, createrole, createdb = conn.execute(
            "SELECT rolsuper, rolbypassrls, rolcreaterole, rolcreatedb "
            "FROM pg_roles WHERE rolname = current_user"
        ).fetchone()
        check(not superuser, "sms_app is not a superuser")
        check(not bypassrls, "sms_app cannot bypass Row-Level Security")
        check(not (createrole or createdb), "sms_app cannot create users or databases")

        member_of = [
            row[0]
            for row in conn.execute(
                "SELECT rolname FROM pg_roles "
                "WHERE pg_has_role(current_user, oid, 'MEMBER') AND rolname <> current_user"
            )
        ]
        check(not member_of, f"sms_app belongs to no other role {member_of or ''}".rstrip())

        can_create = conn.execute("SELECT has_schema_privilege('public', 'CREATE')").fetchone()[0]
        check(not can_create, "sms_app cannot create tables")

        tables = conn.execute(
            "SELECT c.relname, pg_get_userbyid(c.relowner), c.relrowsecurity "
            "FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname"
        ).fetchall()
        if expect_tables:
            check(tables, f"{len(tables)} tables found")
            others = [name for name, owner, _ in tables if owner != MIGRATOR]
            check(not others, f"every table is owned by sms_migrator {others or ''}".rstrip())
            rls = {name: enabled for name, _, enabled in tables}
            for name in RLS_TABLES:
                check(rls.get(name), f"Row-Level Security is on for {name}")
            if "audit_events" in rls:
                can_edit = conn.execute(
                    "SELECT has_table_privilege('audit_events', 'UPDATE') "
                    "OR has_table_privilege('audit_events', 'DELETE')"
                ).fetchone()[0]
                check(not can_edit, "audit events cannot be changed or deleted")
            version = conn.execute("SELECT version_num FROM alembic_version").fetchone()
            print(f"Database: {database}, migration {version[0] if version else 'none'}")
        else:
            check(not tables, "database is empty, ready for migrations")
            print(f"Database: {database}")

    for passed, message in results:
        print(f"  {'ok  ' if passed else 'FAIL'}  {message}")
    return all(passed for passed, _ in results)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("create", "check", "rotate"))
    args = parser.parse_args()
    try:
        if args.command == "create":
            create()
        elif args.command == "rotate":
            rotate()
        else:
            if not ENV_FILE.exists():
                raise SetupError(f"{ENV_FILE.name} not found. Run the create command first.")
            database_url = dotenv_values(ENV_FILE).get("DATABASE_URL")
            if not database_url:
                raise SetupError(f"DATABASE_URL is missing from {ENV_FILE.name}.")
            if not run_checks(database_url):
                raise SetupError("Some checks failed. Do not deploy; share the output above.")
    except SetupError as error:
        sys.exit(f"Stopped: {error}")
    except psycopg.Error as error:
        # The message names the problem (for example a refused password or an
        # unknown host) but never contains a password.
        sys.exit(f"Stopped: database error: {type(error).__name__}: {error}")


if __name__ == "__main__":
    main()
