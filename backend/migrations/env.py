"""Alembic migration environment.

Generated by Flask-Migrate, then changed so that migrations always connect as
the schema-owning user (MIGRATION_DATABASE_URL), never as the runtime app user.
"""

import logging
from logging.config import fileConfig

from alembic import context
from flask import current_app
from sqlalchemy import create_engine, pool

config = context.config
# Keep the app's own loggers working after Alembic configures logging.
fileConfig(config.config_file_name, disable_existing_loggers=False)
logger = logging.getLogger("alembic.env")

target_db = current_app.extensions["migrate"].db


def get_migration_url() -> str:
    url = current_app.config.get("MIGRATION_DATABASE_URI")
    if not url:
        raise RuntimeError(
            "MIGRATION_DATABASE_URL must be set to run migrations. See backend/.env.example."
        )
    return url


def get_metadata():
    if hasattr(target_db, "metadatas"):
        return target_db.metadatas[None]
    return target_db.metadata


def run_migrations_offline():
    """Generate SQL without connecting (`flask db upgrade --sql`)."""
    context.configure(
        url=get_migration_url(),
        target_metadata=get_metadata(),
        literal_binds=True,
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online():
    """Connect as the migration user and apply migrations."""

    # Prevent an empty migration from being generated when nothing changed.
    def process_revision_directives(context, revision, directives):
        if getattr(config.cmd_opts, "autogenerate", False):
            script = directives[0]
            if script.upgrade_ops.is_empty():
                directives[:] = []
                logger.info("No changes in schema detected.")

    conf_args = current_app.extensions["migrate"].configure_args
    if conf_args.get("process_revision_directives") is None:
        conf_args["process_revision_directives"] = process_revision_directives

    # A separate, short-lived engine: never the app's pooled sms_app connection.
    connectable = create_engine(get_migration_url(), poolclass=pool.NullPool)

    try:
        with connectable.connect() as connection:
            context.configure(
                connection=connection,
                target_metadata=get_metadata(),
                **conf_args,
            )

            with context.begin_transaction():
                context.run_migrations()
    finally:
        connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
